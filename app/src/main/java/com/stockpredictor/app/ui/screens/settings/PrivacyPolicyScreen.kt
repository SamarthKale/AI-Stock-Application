@Composable
fun PrivacyPolicyScreen(onBack: () -> Unit) {
    Column(modifier = Modifier.fillMaxSize().background(ClayColor.Background)) {
        ClayAppBar(title = "Privacy Policy", onBack = onBack)
        LazyColumn(
            modifier = Modifier.weight(1f).fillMaxWidth(),
            contentPadding = PaddingValues(ClaySpacing.Lg),
            verticalArrangement = Arrangement.spacedBy(ClaySpacing.Md),
        ) {
            item {
                Text(
                    "This page explains what data AI Crypto Predictor collects and why, in plain " +
                        "language.",
                    color = ClayColor.TextSecondary,
                    style = MaterialTheme.typography.bodyMedium,
                )
            }
            items(sections) { section ->
                ClayCard(modifier = Modifier.fillMaxWidth()) {
                    Column {
                        Text(
                            section.title,
                            color = ClayColor.TextPrimary,
                            style = MaterialTheme.typography.titleMedium,
                            fontWeight = FontWeight.Bold,
                        )
                        Text(
                            section.body,
                            color = ClayColor.TextSecondary,
                            style = MaterialTheme.typography.bodyMedium,
                        )
                    }
                }
            }
        }
    }
}
